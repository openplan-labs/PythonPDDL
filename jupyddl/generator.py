NUMERIC_DOMAIN = """\
;; Transport with fuel -- exercises numeric fluents.
(define (domain numeric-transport)
  (:requirements :strips :typing :numeric-fluents)
  (:types truck location package - object)
  (:predicates
    (at ?t - truck ?l - location)
    (road ?a ?b - location)
    (carrying ?p - package ?t - truck)
    (package-at ?p - package ?l - location))
  (:functions
    (fuel ?t - truck)
    (distance ?a ?b - location))

  (:action drive
    :parameters (?t - truck ?from ?to - location)
    :precondition (and (at ?t ?from) (road ?from ?to)
                       (>= (fuel ?t) (distance ?from ?to)))
    :effect (and (not (at ?t ?from)) (at ?t ?to)
                 (decrease (fuel ?t) (distance ?from ?to))))

  (:action refuel
    :parameters (?t - truck)
    :precondition (< (fuel ?t) 40)
    :effect (assign (fuel ?t) 60))

  (:action load
    :parameters (?p - package ?t - truck ?l - location)
    :precondition (and (at ?t ?l) (package-at ?p ?l))
    :effect (and (not (package-at ?p ?l)) (carrying ?p ?t)))

  (:action unload
    :parameters (?p - package ?t - truck ?l - location)
    :precondition (and (at ?t ?l) (carrying ?p ?t))
    :effect (and (not (carrying ?p ?t)) (package-at ?p ?l))))
"""


def generate_numeric_transport(size: int = 2, seed: int = 0, locations: int = 4):
    """``size`` packages on a fuel-limited road network."""
    rng = random.Random(seed)
    locations = max(2, locations)
    places = _objects("loc", locations)
    packages = _objects("pkg", max(1, size))

    init = ["(at truck1 loc1)", "(= (fuel truck1) 50)"]
    for a, b in zip(places, places[1:]):
        distance = rng.choice([10, 15, 20])
        init.append(f"(road {a} {b})")
        init.append(f"(road {b} {a})")
        init.append(f"(= (distance {a} {b}) {distance})")
        init.append(f"(= (distance {b} {a}) {distance})")

    goals = []
    for package in packages:
        init.append(f"(package-at {package} {places[0]})")
        goals.append(f"(package-at {package} {places[-1]})")

    problem = f"""\
;; {len(packages)} packages, {locations} locations, seed {seed}
(define (problem numeric-transport-{len(packages)}-{seed})
  (:domain numeric-transport)
  (:objects
    truck1 - truck
    {' '.join(places)} - location
    {' '.join(packages)} - package)
  (:init
    {chr(10).join('    ' + f for f in init).strip()})
  (:goal (and
    {chr(10).join('    ' + g for g in goals).strip()})))
"""
    return NUMERIC_DOMAIN, problem


