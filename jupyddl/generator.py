# rovers (ADL: disjunction + quantification)
# --------------------------------------------------------------------------
ROVERS_DOMAIN = """\
;; Rovers -- exercises disjunctive and quantified preconditions.
(define (domain rovers)
  (:requirements :strips :typing :adl)
  (:types rover waypoint objective - object)
  (:predicates
    (at ?r - rover ?w - waypoint)
    (can-traverse ?a ?b - waypoint)
    (visible ?o - objective ?w - waypoint)
    (imaged ?o - objective)
    (sampled ?w - waypoint)
    (analysed ?w - waypoint)
    (reported ?o - objective))

  (:action navigate
    :parameters (?r - rover ?from ?to - waypoint)
    :precondition (and (at ?r ?from) (can-traverse ?from ?to))
    :effect (and (not (at ?r ?from)) (at ?r ?to)))

  (:action sample
    :parameters (?r - rover ?w - waypoint)
    :precondition (and (at ?r ?w) (not (sampled ?w)))
    :effect (sampled ?w))

  (:action analyse
    :parameters (?w - waypoint)
    :precondition (sampled ?w)
    :effect (analysed ?w))

  ;; An objective can be imaged from any waypoint that sees it.
  (:action image
    :parameters (?r - rover ?o - objective)
    :precondition (exists (?w - waypoint) (and (at ?r ?w) (visible ?o ?w)))
    :effect (imaged ?o))

  ;; Reporting accepts either a picture or a full sample analysis.
  (:action report
    :parameters (?o - objective)
    :precondition (or (imaged ?o)
                      (exists (?w - waypoint)
                              (and (visible ?o ?w) (analysed ?w))))
    :effect (reported ?o)))
"""


def generate_rovers(size: int = 3, seed: int = 0, waypoints: int = 5):
    """``size`` objectives over a connected waypoint graph. Uses `or` and `exists`."""
    rng = random.Random(seed)
    waypoints = max(2, waypoints)
    points = _objects("wp", waypoints)
    objectives = _objects("obj", max(1, size))

    init = ["(at rover1 wp1)"]
    # A spanning path guarantees the graph is connected, so every instance is
    # solvable; the extra edges just give the planner choices.
    for a, b in zip(points, points[1:]):
        init.append(f"(can-traverse {a} {b})")
        init.append(f"(can-traverse {b} {a})")
    for _ in range(waypoints):
        a, b = rng.sample(points, 2)
        init.append(f"(can-traverse {a} {b})")

    for objective in objectives:
        for point in rng.sample(points, rng.randint(1, min(2, len(points)))):
            init.append(f"(visible {objective} {point})")

    problem = f"""\
;; {len(objectives)} objectives, {waypoints} waypoints, seed {seed}
(define (problem rovers-{len(objectives)}-{seed})
  (:domain rovers)
  (:objects
    rover1 - rover
    {' '.join(points)} - waypoint
    {' '.join(objectives)} - objective)
  (:init
    {chr(10).join('    ' + f for f in sorted(set(init))).strip()})
  (:goal (and
    {chr(10).join(f'    (reported {o})' for o in objectives).strip()})))
"""
    return ROVERS_DOMAIN, problem


