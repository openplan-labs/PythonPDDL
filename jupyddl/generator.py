LOGISTICS_DOMAIN = """\
;; Logistics with action costs -- generated by jupyddl.generator
(define (domain logistics)
  (:requirements :strips :typing :action-costs)
  (:types
    truck airplane - vehicle
    package vehicle - thing
    airport location - place
    city - object)
  (:predicates
    (at ?t - thing ?p - place)
    (in ?p - package ?v - vehicle)
    (in-city ?p - place ?c - city))
  (:functions (total-cost))

  (:action load
    :parameters (?p - package ?v - vehicle ?l - place)
    :precondition (and (at ?p ?l) (at ?v ?l))
    :effect (and (not (at ?p ?l)) (in ?p ?v) (increase (total-cost) 1)))

  (:action unload
    :parameters (?p - package ?v - vehicle ?l - place)
    :precondition (and (in ?p ?v) (at ?v ?l))
    :effect (and (not (in ?p ?v)) (at ?p ?l) (increase (total-cost) 1)))

  (:action drive
    :parameters (?t - truck ?from - place ?to - place ?c - city)
    :precondition (and (at ?t ?from) (in-city ?from ?c) (in-city ?to ?c))
    :effect (and (not (at ?t ?from)) (at ?t ?to) (increase (total-cost) 2)))

  (:action fly
    :parameters (?a - airplane ?from - airport ?to - airport)
    :precondition (at ?a ?from)
    :effect (and (not (at ?a ?from)) (at ?a ?to) (increase (total-cost) 6))))
"""


def generate_logistics(size: int = 3, seed: int = 0, cities: int = 2):
    """``size`` packages across ``cities`` cities, each with an airport and depot."""
    rng = random.Random(seed)
    cities = max(2, cities)
    packages = _objects("pkg", max(1, size))
    city_names = _objects("city", cities)
    airports = [f"apt{i + 1}" for i in range(cities)]
    depots = [f"depot{i + 1}" for i in range(cities)]
    trucks = [f"truck{i + 1}" for i in range(cities)]

    init = ["(= (total-cost) 0)"]
    for i in range(cities):
        init.append(f"(in-city {airports[i]} {city_names[i]})")
        init.append(f"(in-city {depots[i]} {city_names[i]})")
        init.append(f"(at {trucks[i]} {depots[i]})")
    init.append(f"(at plane1 {airports[0]})")

    goals = []
    for package in packages:
        source = rng.randrange(cities)
        target = rng.randrange(cities)
        while target == source and cities > 1:
            target = rng.randrange(cities)
        init.append(f"(at {package} {rng.choice([airports[source], depots[source]])})")
        goals.append(f"(at {package} {rng.choice([airports[target], depots[target]])})")

    problem = f"""\
;; {len(packages)} packages, {cities} cities, seed {seed}
(define (problem logistics-{len(packages)}-{seed})
  (:domain logistics)
  (:objects
    {' '.join(city_names)} - city
    {' '.join(trucks)} - truck
    plane1 - airplane
    {' '.join(packages)} - package
    {' '.join(airports)} - airport
    {' '.join(depots)} - location)
  (:init
    {chr(10).join('    ' + f for f in init).strip()})
  (:goal (and
    {chr(10).join('    ' + g for g in goals).strip()}))
  (:metric minimize (total-cost)))
"""
    return LOGISTICS_DOMAIN, problem


