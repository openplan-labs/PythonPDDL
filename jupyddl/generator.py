TEMPORAL_DOMAIN = """\
;; Workshop -- exercises durative actions (sequential compilation).
(define (domain workshop)
  (:requirements :strips :typing :durative-actions)
  (:types part - object)
  (:predicates
    (cut ?p - part)
    (drilled ?p - part)
    (painted ?p - part)
    (finished ?p - part))

  (:durative-action cut
    :parameters (?p - part)
    :duration (= ?duration 2)
    :condition (and (at start (not (cut ?p))))
    :effect (and (at end (cut ?p))))

  (:durative-action drill
    :parameters (?p - part)
    :duration (= ?duration 3)
    :condition (and (over all (cut ?p)))
    :effect (and (at end (drilled ?p))))

  (:durative-action paint
    :parameters (?p - part)
    :duration (= ?duration 5)
    :condition (and (over all (drilled ?p)))
    :effect (and (at end (painted ?p))))

  (:durative-action inspect
    :parameters (?p - part)
    :duration (= ?duration 1)
    :condition (and (over all (painted ?p)))
    :effect (and (at end (finished ?p)))))
"""


def generate_temporal_workshop(size: int = 2, seed: int = 0):
    """``size`` parts through a cut/drill/paint/inspect pipeline, with durations."""
    parts = _objects("part", max(1, size))
    problem = f"""\
;; {len(parts)} parts, seed {seed}
(define (problem workshop-{len(parts)}-{seed})
  (:domain workshop)
  (:objects {' '.join(parts)} - part)
  (:init )
  (:goal (and
    {chr(10).join(f'    (finished {p})' for p in parts).strip()})))
"""
    return TEMPORAL_DOMAIN, problem


