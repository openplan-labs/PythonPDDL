"""Generate PDDL domains and problems, reproducibly.

Benchmarks live or die on their instance set, and hand-writing a scaling ladder
is tedious. Each generator here takes a size and a ``seed`` and emits PDDL text,
so a whole difficulty curve is one comprehension — and re-running the same seed
gives byte-identical files, which is what makes a published experiment
reproducible.

::

    from jupyddl.generator import generate, GENERATORS

    domain, problem = generate("blocksworld", size=10, seed=7)
    ladder = [generate("gripper", size=n, seed=1) for n in range(2, 12)]

Every generator is exercised by the test suite, which grounds and solves what it
produces — a generator that emits unsolvable or unparseable PDDL is a bug.
"""

from __future__ import annotations

import random
from typing import Optional

__all__ = [
    "GENERATORS",
    "generate",
    "describe_generators",
    "generate_blocksworld",
    "generate_gripper",
    "generate_logistics",
    "generate_rovers",
    "generate_random_strips",
    "generate_numeric_transport",
    "generate_temporal_workshop",
]


def _objects(prefix: str, count: int) -> list:
    return [f"{prefix}{i + 1}" for i in range(count)]


# --------------------------------------------------------------------------
# blocksworld
# --------------------------------------------------------------------------
BLOCKSWORLD_DOMAIN = """\
;; Blocksworld -- generated by jupyddl.generator
(define (domain blocksworld)
  (:requirements :strips :typing)
  (:types block - object)
  (:predicates
    (on ?x - block ?y - block)
    (ontable ?x - block)
    (clear ?x - block)
    (handempty)
    (holding ?x - block))

  (:action pick-up
    :parameters (?x - block)
    :precondition (and (clear ?x) (ontable ?x) (handempty))
    :effect (and (not (ontable ?x)) (not (clear ?x))
                 (not (handempty)) (holding ?x)))

  (:action put-down
    :parameters (?x - block)
    :precondition (holding ?x)
    :effect (and (not (holding ?x)) (clear ?x) (handempty) (ontable ?x)))

  (:action stack
    :parameters (?x - block ?y - block)
    :precondition (and (holding ?x) (clear ?y))
    :effect (and (not (holding ?x)) (not (clear ?y))
                 (clear ?x) (handempty) (on ?x ?y)))

  (:action unstack
    :parameters (?x - block ?y - block)
    :precondition (and (on ?x ?y) (clear ?x) (handempty))
    :effect (and (holding ?x) (clear ?y) (not (clear ?x))
                 (not (handempty)) (not (on ?x ?y)))))
"""


def _random_towers(blocks, rng) -> list:
    """Partition ``blocks`` into a random set of towers (bottom-first)."""
    shuffled = list(blocks)
    rng.shuffle(shuffled)
    towers: list = []
    index = 0
    while index < len(shuffled):
        height = rng.randint(1, max(1, len(shuffled) - index))
        towers.append(shuffled[index : index + height])
        index += height
    return towers


def _tower_facts(towers) -> list:
    facts = []
    for tower in towers:
        facts.append(f"(ontable {tower[0]})")
        for lower, upper in zip(tower, tower[1:]):
            facts.append(f"(on {upper} {lower})")
        facts.append(f"(clear {tower[-1]})")
    return facts


def generate_blocksworld(size: int = 6, seed: int = 0):
    """``size`` blocks in random towers, to be rearranged into other towers."""
    rng = random.Random(seed)
    blocks = _objects("b", max(2, size))
    start = _random_towers(blocks, rng)
    goal_towers = _random_towers(blocks, rng)
    while goal_towers == start and len(blocks) > 2:
        goal_towers = _random_towers(blocks, rng)

    goal_facts = []
    for tower in goal_towers:
        goal_facts.append(f"(ontable {tower[0]})")
        for lower, upper in zip(tower, tower[1:]):
            goal_facts.append(f"(on {upper} {lower})")

    problem = f"""\
;; {len(blocks)} blocks, seed {seed} -- generated by jupyddl.generator
(define (problem blocksworld-{len(blocks)}-{seed})
  (:domain blocksworld)
  (:objects {' '.join(blocks)} - block)
  (:init
    (handempty)
    {chr(10).join('    ' + f for f in _tower_facts(start)).strip()})
  (:goal (and
    {chr(10).join('    ' + f for f in goal_facts).strip()})))
"""
    return BLOCKSWORLD_DOMAIN, problem


