GRIPPER_DOMAIN = """\
;; Gripper -- generated by jupyddl.generator
(define (domain gripper)
  (:requirements :strips :typing)
  (:types room ball gripper - object)
  (:predicates
    (at-robby ?r - room)
    (at ?b - ball ?r - room)
    (free ?g - gripper)
    (carry ?b - ball ?g - gripper))

  (:action move
    :parameters (?from - room ?to - room)
    :precondition (at-robby ?from)
    :effect (and (at-robby ?to) (not (at-robby ?from))))

  (:action pick
    :parameters (?b - ball ?r - room ?g - gripper)
    :precondition (and (at ?b ?r) (at-robby ?r) (free ?g))
    :effect (and (carry ?b ?g) (not (at ?b ?r)) (not (free ?g))))

  (:action drop
    :parameters (?b - ball ?r - room ?g - gripper)
    :precondition (and (carry ?b ?g) (at-robby ?r))
    :effect (and (at ?b ?r) (free ?g) (not (carry ?b ?g)))))
"""


def generate_gripper(size: int = 4, seed: int = 0, grippers: int = 2):
    """``size`` balls to move from room A to room B. Plan length grows linearly.

    Unlike every other generator here, ``seed`` does not vary the instance:
    in gripper every ball starts in room A and must end in room B, so
    ``size`` and ``grippers`` determine the problem completely. The seed
    reaches only the problem name, which keeps generated files distinct.

    The consequence is worth stating because it is easy to miss: a
    train/test split that varies the seed and holds the size fixed produces
    the *same instance* twice for this domain. Vary ``size`` instead.
    """
    balls = _objects("ball", max(1, size))
    hands = _objects("gripper", max(1, grippers))
    init = ["(at-robby rooma)"]
    init += [f"(free {g})" for g in hands]
    init += [f"(at {b} rooma)" for b in balls]

    problem = f"""\
;; {len(balls)} balls, {len(hands)} grippers, seed {seed}
(define (problem gripper-{len(balls)}-{seed})
  (:domain gripper)
  (:objects
    rooma roomb - room
    {' '.join(balls)} - ball
    {' '.join(hands)} - gripper)
  (:init
    {chr(10).join('    ' + f for f in init).strip()})
  (:goal (and
    {chr(10).join(f'    (at {b} roomb)' for b in balls).strip()})))
"""
    return GRIPPER_DOMAIN, problem


