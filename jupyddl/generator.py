# random STRIPS
# --------------------------------------------------------------------------
def generate_random_strips(
    size: int = 8,
    seed: int = 0,
    actions: int = 10,
    goal_size: int = 3,
):
    """A random STRIPS instance built backwards from a guaranteed solution.

    Purely random operators almost always give an unsolvable problem, which
    makes for a useless benchmark. Instead this plants a random *chain*: each
    step in the chain has an action that turns the previous state into the next,
    so a plan of known length exists. The remaining actions are noise the
    planner has to search past.
    """
    rng = random.Random(seed)
    size = max(4, size)
    facts = [f"p{i + 1}" for i in range(size)]
    chain_length = max(2, min(actions // 2, size))

    init_facts = set(rng.sample(facts, max(1, size // 3)))
    state = set(init_facts)
    operators = []

    # --- the planted solution ---------------------------------------------
    for step in range(chain_length):
        candidates = [f for f in facts if f not in state]
        if not candidates:
            break
        added = rng.choice(candidates)
        precondition = sorted(rng.sample(sorted(state), min(2, len(state))))
        deleted = []
        if len(state) > 1 and rng.random() < 0.4:
            deleted = [
                (
                    rng.choice([f for f in sorted(state) if f not in precondition])
                    if len(state) > len(precondition)
                    else None
                )
            ]
            deleted = [d for d in deleted if d]
        operators.append((f"solve{step + 1}", precondition, [added], deleted))
        state.add(added)
        state.difference_update(deleted)

    goal_facts = sorted(rng.sample(sorted(state), min(goal_size, len(state))))

    # --- distractors -------------------------------------------------------
    for index in range(max(0, actions - len(operators))):
        precondition = sorted(rng.sample(facts, rng.randint(1, 2)))
        added = sorted(rng.sample(facts, rng.randint(1, 2)))
        deleted = [f for f in rng.sample(facts, 1) if f not in added]
        operators.append((f"noise{index + 1}", precondition, added, deleted))

    def action_text(name, pre, add, delete):
        conditions = " ".join(f"({p})" for p in pre) or ""
        effects = " ".join(f"({a})" for a in add)
        effects += " " + " ".join(f"(not ({d}))" for d in delete)
        return (
            f"  (:action {name}\n"
            f"    :precondition (and {conditions})\n"
            f"    :effect (and {effects.strip()}))"
        )

    domain = "\n".join(
        [
            ";; Random STRIPS -- generated by jupyddl.generator",
            f"(define (domain random-strips-{size}-{seed})",
            "  (:requirements :strips)",
            "  (:predicates " + " ".join(f"({f})" for f in facts) + ")",
            "",
            "\n\n".join(action_text(*op) for op in operators),
            ")",
        ]
    )
    problem = f"""\
;; {size} facts, {len(operators)} actions, seed {seed}
(define (problem random-strips-{size}-{seed})
  (:domain random-strips-{size}-{seed})
  (:init {' '.join(f'({f})' for f in sorted(init_facts))})
  (:goal (and {' '.join(f'({f})' for f in goal_facts)})))
"""
    return domain, problem


