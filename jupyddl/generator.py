# What each generator is meant to stress, for the CLI and the playground.
GENERATOR_NOTES = {
    "blocksworld": "Classic block stacking. Deep plans, heavy plateaus.",
    "gripper": "Balls between two rooms. High branching factor.",
    "logistics": "Trucks and a plane with action costs.",
    "rovers": "ADL: disjunctive and existential preconditions.",
    "numeric-transport": "Numeric fluents: fuel consumption and refuelling.",
    "workshop": "Durative actions; plans report a makespan.",
    "random-strips": "Random operators around a planted solution chain.",
}


def generate(kind: str, size: int = 4, seed: int = 0, **kwargs):
    """Generate ``(domain_text, problem_text)`` for a named generator."""
    try:
        factory = GENERATORS[kind]
    except KeyError:
        raise ValueError(
            f"Unknown generator '{kind}'. Available: {sorted(GENERATORS)}"
        ) from None
    return factory(size=size, seed=seed, **kwargs)


def describe_generators() -> list:
    """Serialisable metadata for the CLI and the web workbench."""
    return [
        {"name": name, "summary": GENERATOR_NOTES.get(name, "")}
        for name in sorted(GENERATORS)
    ]


def write_instance(
    kind: str,
    folder: str,
    size: int = 4,
    seed: int = 0,
    name: Optional[str] = None,
    **kwargs,
) -> str:
    """Generate an instance and write ``<folder>/<name>/{domain,problem}.pddl``."""
    import os

    domain, problem = generate(kind, size=size, seed=seed, **kwargs)
    target = os.path.join(folder, name or f"{kind}-{size:02d}-{seed}")
    os.makedirs(target, exist_ok=True)
    with open(os.path.join(target, "domain.pddl"), "w", encoding="utf-8") as handle:
        handle.write(domain)
    with open(os.path.join(target, "problem.pddl"), "w", encoding="utf-8") as handle:
        handle.write(problem)
    return target
